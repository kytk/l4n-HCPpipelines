#!/bin/bash
# Single-node Slurm inside the container, for fsl_sub
# Author: K. Nemoto
# Version: 1.0.0
#
# Called by startup.sh as root, before it switches to brain. Writes the
# configuration for this host and starts munged, slurmctld and slurmd.
#
# CPUs, memory and the host name differ between machines (and between
# containers: Docker gives every new container a new host name), so nothing of
# this is baked into the image; it is regenerated on every start.
#
# /etc/fsl_sub.yml is written only when Slurm came up. bash_aliases exports
# FSLSUB_CONF only when that file exists, so without it fsl_sub falls back to
# its built-in "shell" method (run in place). That covers:
#   - SLURM=off (docker run -e SLURM=off)
#   - not running as root (Apptainer)
#   - any daemon failing to start
#
# No cgroups (ProctrackType=proctrack/linuxproc, TaskPlugin=task/none): an
# unprivileged container cannot manage them. Memory is therefore only used to
# decide how many jobs run at once; it is not enforced.

set -u

FSLSUB_CONF=/etc/fsl_sub.yml
SLURM_CONF=/etc/slurm/slurm.conf
PARTITION=main
# Memory given to a job that does not ask for any (fsl_sub without -R; the
# HCP Pipelines batch scripts never pass -R). Without a default Slurm gives
# such a job the whole node, and jobs would run one at a time.
DEF_MEM_MB=8192
# Kept back from Slurm for the desktop and the shell
RESERVE_MB=2048

log() { echo "slurm-init: $*"; }

# Never leave a configuration from an earlier start behind: fsl_sub would
# submit to a Slurm that is not running.
rm -f "$FSLSUB_CONF"

case "${SLURM:-on}" in
    off|OFF|0|no|false)
        log "SLURM=${SLURM}; not starting Slurm (fsl_sub runs jobs in place)"
        exit 0
        ;;
esac

if [[ $(id -u) -ne 0 ]]; then
    log "not running as root; not starting Slurm (fsl_sub runs jobs in place)"
    exit 0
fi

#------------------------------------------------------------------------------
# Resources of this host
#------------------------------------------------------------------------------
host=$(hostname -s)
# nproc honours --cpuset-cpus, but not the --cpus quota
cpus=$(nproc)

mem_mb=$(awk '/^MemTotal:/ {print int($2 / 1024)}' /proc/meminfo)
# /proc/meminfo shows the host's memory even under docker run --memory;
# use the cgroup limit when there is one (v2, then v1)
for f in /sys/fs/cgroup/memory.max /sys/fs/cgroup/memory/memory.limit_in_bytes; do
    if [[ -r $f ]]; then
        limit=$(cat "$f")
        if [[ $limit =~ ^[0-9]+$ ]]; then
            limit_mb=$((limit / 1024 / 1024))
            if ((limit_mb < mem_mb)); then
                mem_mb=$limit_mb
            fi
        fi
        break
    fi
done

real_mem_mb=$((mem_mb - RESERVE_MB))
if ((real_mem_mb < 1024)); then
    real_mem_mb=1024
fi
def_mem_mb=$DEF_MEM_MB
if ((def_mem_mb > real_mem_mb)); then
    def_mem_mb=$real_mem_mb
fi

log "node ${host}: ${cpus} CPUs, ${real_mem_mb} MB for jobs, ${def_mem_mb} MB per job by default"

#------------------------------------------------------------------------------
# slurm.conf
#------------------------------------------------------------------------------
mkdir -p /etc/slurm /var/spool/slurmctld /var/spool/slurmd /var/log/slurm /run/slurm
chown slurm:slurm /var/spool/slurmctld /var/log/slurm /run/slurm

cat > "$SLURM_CONF" <<EOF
# Generated by /usr/local/bin/slurm-init.sh on every container start.
# Edits are lost on the next start; change slurm-init.sh instead.
ClusterName=l4n
SlurmctldHost=${host}
SlurmUser=slurm
AuthType=auth/munge
MpiDefault=none
MailProg=/bin/true

# No cgroups in an unprivileged container
ProctrackType=proctrack/linuxproc
TaskPlugin=task/none
JobAcctGatherType=jobacct_gather/none
AccountingStorageType=accounting_storage/none
JobCompType=jobcomp/none

SchedulerType=sched/backfill
SelectType=select/cons_tres
SelectTypeParameters=CR_Core_Memory
DefMemPerNode=${def_mem_mb}
# A node that was down (container stopped) is usable again once slurmd
# registers
ReturnToService=2

StateSaveLocation=/var/spool/slurmctld
SlurmdSpoolDir=/var/spool/slurmd
SlurmctldPidFile=/run/slurm/slurmctld.pid
SlurmdPidFile=/run/slurm/slurmd.pid
SlurmctldLogFile=/var/log/slurm/slurmctld.log
SlurmdLogFile=/var/log/slurm/slurmd.log

NodeName=${host} CPUs=${cpus} RealMemory=${real_mem_mb} State=UNKNOWN
PartitionName=${PARTITION} Nodes=ALL Default=YES MaxTime=INFINITE State=UP
EOF

#------------------------------------------------------------------------------
# Daemons
#------------------------------------------------------------------------------
# pid files survive docker stop/start (the container file system is kept)
rm -f /run/slurm/*.pid /run/munge/munged.pid

# munge: a fresh key on every start. Only this one node uses it.
mkdir -p /run/munge
chown munge:munge /run/munge
mungekey --create --force --keyfile=/etc/munge/munge.key
chown munge:munge /etc/munge/munge.key
chmod 400 /etc/munge/munge.key
if ! runuser -u munge -- /usr/sbin/munged; then
    log "munged failed to start; fsl_sub runs jobs in place"
    exit 0
fi

if ! /usr/sbin/slurmctld; then
    log "slurmctld failed to start (see /var/log/slurm/slurmctld.log); fsl_sub runs jobs in place"
    exit 0
fi
if ! /usr/sbin/slurmd; then
    log "slurmd failed to start (see /var/log/slurm/slurmd.log); fsl_sub runs jobs in place"
    exit 0
fi

# Wait until the node accepts jobs
state=
for _ in $(seq 1 30); do
    state=$(sinfo -h -n "$host" -o %T 2>/dev/null)
    case "$state" in
        idle*|mixed*|alloc*) break ;;
    esac
    sleep 1
done
case "$state" in
    idle*|mixed*|alloc*) ;;
    *)
        log "node ${host} is '${state}' after 30 s (see /var/log/slurm/); fsl_sub runs jobs in place"
        exit 0
        ;;
esac

#------------------------------------------------------------------------------
# fsl_sub
#------------------------------------------------------------------------------
cat > "$FSLSUB_CONF" <<EOF
# Generated by /usr/local/bin/slurm-init.sh on every container start.
# Edits are lost on the next start; put your own settings in ~/.fsl_sub.yml,
# which fsl_sub reads on top of this file.
method: slurm
method_opts:
  slurm:
    queues: True
    # Hand the shell's environment (FSLDIR, FREESURFER_HOME, PATH, ...) to
    # the job
    copy_environment: True
    has_parallel_envs: False
    # True makes fsl_sub ask sacctmgr for the user's account; there is no
    # accounting database
    projects: False
    memory_in_gb: False
    # Pass -R on to Slurm as --mem
    notify_ram_usage: True
    set_time_limit: False
    array_holds: True
    array_limit: True
    mail_support: False
    script_conf: True
    keep_jobscript: False
    preserve_modules: False
    strict_dependencies: False
    # fsl_sub called from inside a job (bedpostx, ICA-FIX, ... in HCP
    # Pipelines) runs in place instead of submitting another job
    allow_nested_queuing: False
queues:
  ${PARTITION}:
    default: true
    # What "fsl_sub_config slurm" writes for MaxTime=INFINITE
    time: 527039
    max_slots: ${cpus}
    max_size: $((real_mem_mb / 1024))
    # Required, even though Slurm does not use it
    slot_size: null
EOF
chmod 644 "$FSLSUB_CONF"

log "Slurm is up; fsl_sub submits to partition '${PARTITION}'"
